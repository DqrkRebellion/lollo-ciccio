-- TicketSMS automated sync tables (read-only for authenticated app users; written by GitHub Action via service_role)

CREATE TABLE IF NOT EXISTS public.ticketsms_events (
  event_id bigint PRIMARY KEY,
  name text NOT NULL DEFAULT '',
  event_date date,
  weekday text,
  month text,
  year integer,
  location_name text,
  location_full text,
  cover_image_url text,
  dash_url text,
  shop_url text,
  is_active boolean NOT NULL DEFAULT true,
  is_canceled boolean NOT NULL DEFAULT false,
  tickets_sent integer NOT NULL DEFAULT 0,
  total_profit numeric(12, 2) NOT NULL DEFAULT 0.00,
  entered integer NOT NULL DEFAULT 0,
  time_to_end text,
  synced_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ticketsms_events_active_date
  ON public.ticketsms_events (is_active, event_date);

CREATE TABLE IF NOT EXISTS public.ticketsms_ticket_types (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id bigint NOT NULL REFERENCES public.ticketsms_events(event_id) ON DELETE CASCADE,
  ticket_type_id text NOT NULL,
  name text NOT NULL DEFAULT '',
  description text,
  price numeric(10, 2) NOT NULL DEFAULT 0.00,
  sold integer NOT NULL DEFAULT 0,
  entered integer NOT NULL DEFAULT 0,
  total numeric(12, 2) NOT NULL DEFAULT 0.00,
  online_sold integer NOT NULL DEFAULT 0,
  online_total numeric(12, 2) NOT NULL DEFAULT 0.00,
  one_to_one_sold integer NOT NULL DEFAULT 0,
  one_to_one_total numeric(12, 2) NOT NULL DEFAULT 0.00,
  box_office_sold integer NOT NULL DEFAULT 0,
  box_office_total numeric(12, 2) NOT NULL DEFAULT 0.00,
  synced_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (event_id, ticket_type_id)
);

CREATE INDEX IF NOT EXISTS idx_ticketsms_ticket_types_event
  ON public.ticketsms_ticket_types (event_id);

CREATE TABLE IF NOT EXISTS public.ticketsms_team_sales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id bigint NOT NULL REFERENCES public.ticketsms_events(event_id) ON DELETE CASCADE,
  pr_id text NOT NULL,
  pr_name text NOT NULL DEFAULT '',
  sub_pr_count integer NOT NULL DEFAULT 0,
  is_self boolean NOT NULL DEFAULT false,
  sold integer NOT NULL DEFAULT 0,
  entered integer NOT NULL DEFAULT 0,
  total numeric(12, 2) NOT NULL DEFAULT 0.00,
  synced_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (event_id, pr_id)
);

CREATE INDEX IF NOT EXISTS idx_ticketsms_team_sales_event_sold
  ON public.ticketsms_team_sales (event_id, sold DESC);

CREATE TABLE IF NOT EXISTS public.ticketsms_sync_status (
  id integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  status text NOT NULL DEFAULT 'ok' CHECK (status IN ('ok', 'session_expired', 'error')),
  events_synced integer NOT NULL DEFAULT 0,
  message text NOT NULL DEFAULT '',
  synced_at timestamptz
);

-- Enable RLS: authenticated app users can read; anon blocked; service_role bypasses RLS for sync writes
ALTER TABLE public.ticketsms_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ticketsms_ticket_types ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ticketsms_team_sales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ticketsms_sync_status ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "authenticated_read_ticketsms_events" ON public.ticketsms_events;
CREATE POLICY "authenticated_read_ticketsms_events" ON public.ticketsms_events
  FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS "authenticated_read_ticketsms_ticket_types" ON public.ticketsms_ticket_types;
CREATE POLICY "authenticated_read_ticketsms_ticket_types" ON public.ticketsms_ticket_types
  FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS "authenticated_read_ticketsms_team_sales" ON public.ticketsms_team_sales;
CREATE POLICY "authenticated_read_ticketsms_team_sales" ON public.ticketsms_team_sales
  FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS "authenticated_read_ticketsms_sync_status" ON public.ticketsms_sync_status;
CREATE POLICY "authenticated_read_ticketsms_sync_status" ON public.ticketsms_sync_status
  FOR SELECT TO authenticated
  USING (true);

-- Add to Realtime publication so scheduled/manual syncs appear live
DO $$
DECLARE
  tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY[
    'ticketsms_events',
    'ticketsms_ticket_types',
    'ticketsms_team_sales',
    'ticketsms_sync_status'
  ] LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_publication_tables
      WHERE pubname = 'supabase_realtime'
        AND schemaname = 'public'
        AND tablename = tbl
    ) THEN
      EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', tbl);
    END IF;
  END LOOP;
END;
$$;
