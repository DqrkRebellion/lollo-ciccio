-- Integrate TicketSMS events directly inside Lollo & Ciccio Serate (`public.events`)
-- and store exact per-row XLS/CSV report data downloaded from TicketSMS (`action/csvReportEvent.php`).

-- 1. Link public.events 1:1 to public.ticketsms_events
ALTER TABLE public.events
  ADD COLUMN IF NOT EXISTS ticketsms_event_id bigint
  REFERENCES public.ticketsms_events(event_id) ON DELETE SET NULL;

CREATE UNIQUE INDEX IF NOT EXISTS idx_events_ticketsms_event_id_unique
  ON public.events (ticketsms_event_id)
  WHERE ticketsms_event_id IS NOT NULL;

-- 2. Raw TicketSMS XLS/CSV report rows (Promoter x Tipologia x Canale)
CREATE TABLE IF NOT EXISTS public.ticketsms_event_report_rows (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id bigint NOT NULL REFERENCES public.ticketsms_events(event_id) ON DELETE CASCADE,
  promoter_name text NOT NULL DEFAULT '',
  ticket_type text NOT NULL DEFAULT '',
  price numeric(10, 2) NOT NULL DEFAULT 0.00,
  online_qty integer NOT NULL DEFAULT 0,
  online_revenue numeric(12, 2) NOT NULL DEFAULT 0.00,
  one_to_one_qty integer NOT NULL DEFAULT 0,
  one_to_one_revenue numeric(12, 2) NOT NULL DEFAULT 0.00,
  box_office_qty integer NOT NULL DEFAULT 0,
  box_office_revenue numeric(12, 2) NOT NULL DEFAULT 0.00,
  total_qty integer NOT NULL DEFAULT 0,
  total_revenue numeric(12, 2) NOT NULL DEFAULT 0.00,
  row_order integer NOT NULL DEFAULT 0,
  synced_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (event_id, promoter_name, ticket_type, price)
);

CREATE INDEX IF NOT EXISTS idx_ticketsms_report_rows_event_order
  ON public.ticketsms_event_report_rows (event_id, row_order);

-- 3. Strict RLS: authenticated team users read-only; anon blocked; writes via service_role
ALTER TABLE public.ticketsms_event_report_rows ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "authenticated_read_ticketsms_report_rows" ON public.ticketsms_event_report_rows;
CREATE POLICY "authenticated_read_ticketsms_report_rows" ON public.ticketsms_event_report_rows
  FOR SELECT TO authenticated
  USING (true);

-- 4. Atomic replacement RPC for sync script (service_role ONLY)
CREATE OR REPLACE FUNCTION public.replace_ticketsms_report_rows(
  p_event_id bigint,
  p_rows jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  DELETE FROM public.ticketsms_event_report_rows
  WHERE event_id = p_event_id;

  IF p_rows IS NOT NULL AND jsonb_typeof(p_rows) = 'array' AND jsonb_array_length(p_rows) > 0 THEN
    INSERT INTO public.ticketsms_event_report_rows (
      event_id,
      promoter_name,
      ticket_type,
      price,
      online_qty,
      online_revenue,
      one_to_one_qty,
      one_to_one_revenue,
      box_office_qty,
      box_office_revenue,
      total_qty,
      total_revenue,
      row_order,
      synced_at
    )
    SELECT
      p_event_id,
      COALESCE(r->>'promoter_name', ''),
      COALESCE(r->>'ticket_type', ''),
      COALESCE((r->>'price')::numeric(10, 2), 0.00),
      COALESCE((r->>'online_qty')::integer, 0),
      COALESCE((r->>'online_revenue')::numeric(12, 2), 0.00),
      COALESCE((r->>'one_to_one_qty')::integer, 0),
      COALESCE((r->>'one_to_one_revenue')::numeric(12, 2), 0.00),
      COALESCE((r->>'box_office_qty')::integer, 0),
      COALESCE((r->>'box_office_revenue')::numeric(12, 2), 0.00),
      COALESCE((r->>'total_qty')::integer, 0),
      COALESCE((r->>'total_revenue')::numeric(12, 2), 0.00),
      COALESCE((r->>'row_order')::integer, 0),
      COALESCE((r->>'synced_at')::timestamptz, now())
    FROM jsonb_array_elements(p_rows) AS r
    ON CONFLICT (event_id, promoter_name, ticket_type, price) DO UPDATE SET
      online_qty = EXCLUDED.online_qty,
      online_revenue = EXCLUDED.online_revenue,
      one_to_one_qty = EXCLUDED.one_to_one_qty,
      one_to_one_revenue = EXCLUDED.one_to_one_revenue,
      box_office_qty = EXCLUDED.box_office_qty,
      box_office_revenue = EXCLUDED.box_office_revenue,
      total_qty = EXCLUDED.total_qty,
      total_revenue = EXCLUDED.total_revenue,
      row_order = EXCLUDED.row_order,
      synced_at = EXCLUDED.synced_at;
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.replace_ticketsms_report_rows(bigint, jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.replace_ticketsms_report_rows(bigint, jsonb) TO service_role;

-- 5. Enable Supabase Realtime on report rows table
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime'
      AND schemaname = 'public'
      AND tablename = 'ticketsms_event_report_rows'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.ticketsms_event_report_rows;
  END IF;
END;
$$;
